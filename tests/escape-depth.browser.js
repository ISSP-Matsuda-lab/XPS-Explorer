const server = http.createServer((req,res) => {
  try {
    const requested = decodeURIComponent(new URL(req.url,'http://localhost').pathname);
    const target = path.resolve(root, '.' + (requested === '/' ? '/index.html' : requested));
    if (!target.startsWith(root + path.sep) || !/^(?:index\.html|escape-depth\.html|effective-depth\.html|assets[\\/])/.test(path.relative(root,target)) || !contentTypes[path.extname(target)] || !fs.existsSync(target)) { res.writeHead(404); return res.end(); }
    const canonical = fs.realpathSync(target);
    if (canonical !== target) { res.writeHead(403); return res.end(); }
    res.setHeader('Content-Type', contentTypes[path.extname(target)]); res.end(fs.readFileSync(canonical));
  } catch { res.writeHead(500); res.end(); }
});
